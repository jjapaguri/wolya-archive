export type ProductCategory = "top" | "bottom" | "accessory" | "shoes";

export const CATEGORY_LABELS: Record<ProductCategory, string> = {
  top: "상의",
  bottom: "하의",
  accessory: "액세서리",
  shoes: "신발",
};

export const CATEGORIES: ProductCategory[] = ["top", "bottom", "accessory", "shoes"];

/** 홈 코디 교차 슬라이드의 줄 구분 — 윗줄(상의) / 아랫줄(하의) */
export type ProductKind = "top" | "bottom";

/**
 * 진열 채널 — Shop 과 Archive 는 역할이 다르다.
 *
 * `archive` 는 주인장 개인 소장 중고(대부분 1점 한정), `shop` 은 도매 소싱한
 * 재입고 가능한 신상품이다. 값이 없는 상품은 `archive` 로 본다 (`Product.channel` 주석).
 */
export type ProductChannel = "archive" | "shop";

/** 채널이 지정되지 않은 상품의 기본값. 판단이 한 곳에만 있도록 함수로 둔다 */
export function productChannel(product: Product): ProductChannel {
  return product.channel ?? "archive";
}

/**
 * 코디 교차 슬라이드를 렌더하는 최소 개수 (윗줄·아랫줄 각각).
 *
 * 이 구간의 의미는 "지나가는 동안 상의×하의 조합이 계속 바뀐다" 는 것이다.
 * 한쪽이 1건뿐이면 같은 옷이 혼자 도는 그림이라 조합이 바뀌지 않고 재고가
 * 비어 보이기만 한다. 못 미치면 구간 자체를 렌더하지 않는다 —
 * 상의·하의가 각각 이 개수만큼 차면 코드 수정 없이 다시 나타난다.
 */
export const OUTFIT_ROW_MIN_ITEMS = 2;

export type Product = {
  id: number;
  slug: string;
  tag: string;
  /** 대표 이미지 (목록·OG 용) */
  image: string;
  /** 상세 갤러리. [0] 은 image 와 같다 */
  images: string[];
  name: string;
  brand: string;
  size: string;
  /** 판매가 (원). 후르츠 게시가 + 10% 세금 */
  price: number;
  condition: string;
  hook: string;
  fabric: string;
  fit: string;
  measurements: string;
  stock: string;
  recommendedFor: string;
  /** 필터용 분류 — top/bottom/accessory/shoes 4종 고정 */
  category: ProductCategory;
  /**
   * 홈 코디 교차 슬라이드에서 어느 줄에 흐를지.
   * "top" = 윗줄(상의), "bottom" = 아랫줄(하의).
   * **입는 위치가 상·하의가 아닌 품목(가방·신발 등)은 `null`** — 이 구간에서 제외한다.
   * 필터용 `category` 와는 축이 다르다.
   */
  kind: ProductKind | null;
  /**
   * 카드에 한 줄로 노출하는 짧은 실측. 숫자가 세로로 맞도록 tabular-nums 로 그린다.
   * 상세한 실측·원단·핏은 `measurements` 등 상세 페이지 몫이다.
   */
  shortMeasure: string;
  /** 검색·분위기 표현용 해시태그. 분류가 아니다 */
  tags: string;
  /**
   * available: 이미 매입해 보유 중. preorder: 사입 확인 전 예약주문.
   * sold: 원본 매물 생존 체크(`scripts/check-source-availability.mjs`)가 원본이
   * 죽었다고 판정해 내림 — `/shop` `/m/shop` 목록·홈 코디 슬라이드에서 빠지지만
   * 상세페이지는 살아있다(판매완료 표시로 남김, 404 아님). 되돌리기는 사람이 한다.
   */
  status: "available" | "preorder" | "sold";
  /**
   * 어느 페이지에 진열할지.
   *
   * - `"archive"`(기본) — 주인장 개인 소장 중고·1점 한정. `/archive` `/m/archive`
   * - `"shop"` — 도매 소싱해 들여오는 재입고 가능한 신상품. `/shop` `/m/shop`
   *
   * **생략하면 `"archive"` 다.** 지금 원장 전량이 개인 소장분이라 기본값이 곧 현실이고,
   * 필수로 만들면 기존 항목 전부와 DB 매퍼를 같이 고쳐야 해서 선택 필드로 뒀다.
   * 신상품을 등록하는 쪽이 `channel: "shop"` 을 명시한다.
   * (DB 에 컬럼이 생기면 `src/lib/product-queries.ts` 의 `mapRow` 에서 채운다.)
   */
  channel?: ProductChannel;
  /** 판매자 고지(하자·할인가 변동 등). 있으면 상세페이지 하단에 노출 */
  note?: string;
};

